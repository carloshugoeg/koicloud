"""Cross-pond console repair: SERIAL then IDENTITY on one shared Postgres.

Repairing pond A must not leave pond B's first POST /sql as 503 node_unavailable.
Covers alternating and concurrent first-create, repeated queries, sequence INSERTs,
and isolation so koi_console on pond A cannot read pond B's data.
"""

from __future__ import annotations

import asyncio
from dataclasses import dataclass
from uuid import UUID, uuid4

import httpx
import psycopg
import pytest
from httpx import ASGITransport
from psycopg import sql as pg_sql
from sqlalchemy import create_engine, text

from app.core.config import get_settings, to_sync_database_url
from app.core.crypto import encrypt_secret
from app.core.security import hash_token
from app.main import app
from app.modules.ponds.console_role import CONSOLE_ROLE, console_role_password
from tests.db_reset import DEMO_EMAIL, DEMO_PASSWORD, ensure_demo_user, reset_pond_tables
from tests.sql_probe_pond import PROBE_PASSWORD

# Same password as sql_probe_pond so this suite does not desync the
# cluster-wide postgres role used by other real-pond tests.
POND_PASSWORD = PROBE_PASSWORD
HOST = "127.0.0.1"
PORT_SERIAL = 5432
PORT_IDENTITY = 5433
SERIAL_NAME = "cross-serial"
IDENTITY_NAME = "cross-identity"
SERIAL_DB = "cross_serial"
IDENTITY_DB = "cross_identity"
PARALLEL_N = 8


@dataclass(frozen=True, slots=True)
class CrossPonds:
    serial_id: UUID
    identity_id: UUID
    user_id: UUID


def _admin(database: str) -> str:
    base = to_sync_database_url(get_settings().database_url).replace(
        "postgresql+psycopg://", "postgresql://", 1
    )
    return base.rsplit("/", 1)[0] + f"/{database}"


def _drop_console_role() -> None:
    with psycopg.connect(_admin("postgres"), autocommit=True) as conn:
        exists = conn.execute(
            "SELECT 1 FROM pg_roles WHERE rolname = %s",
            (CONSOLE_ROLE,),
        ).fetchone()
        databases = [
            row[0]
            for row in conn.execute(
                """
                SELECT datname FROM pg_database
                WHERE datallowconn AND NOT datistemplate
                """
            ).fetchall()
        ]
    if exists is None:
        return
    for name in databases:
        with psycopg.connect(_admin(name), autocommit=True) as conn:
            conn.execute(
                """
                SELECT pg_terminate_backend(pid)
                FROM pg_stat_activity
                WHERE usename = %s AND pid <> pg_backend_pid()
                """,
                (CONSOLE_ROLE,),
            )
            try:
                conn.execute(f"DROP OWNED BY {CONSOLE_ROLE}")
            except psycopg.Error:
                pass
    with psycopg.connect(_admin("postgres"), autocommit=True) as conn:
        conn.execute(f"DROP ROLE IF EXISTS {CONSOLE_ROLE}")


def _ensure_postgres_role() -> None:
    with psycopg.connect(_admin("postgres"), autocommit=True) as conn:
        exists = conn.execute("SELECT 1 FROM pg_roles WHERE rolname = 'postgres'").fetchone()
        if exists is None:
            conn.execute(
                pg_sql.SQL("CREATE ROLE postgres LOGIN SUPERUSER PASSWORD {}").format(
                    pg_sql.Literal(POND_PASSWORD)
                )
            )
        else:
            conn.execute(
                pg_sql.SQL("ALTER ROLE postgres WITH LOGIN SUPERUSER PASSWORD {}").format(
                    pg_sql.Literal(POND_PASSWORD)
                )
            )


def _recreate_database(database: str) -> None:
    with psycopg.connect(_admin("postgres"), autocommit=True) as conn:
        conn.execute(
            """
            SELECT pg_terminate_backend(pid)
            FROM pg_stat_activity
            WHERE datname = %s AND pid <> pg_backend_pid()
            """,
            (database,),
        )
        conn.execute(pg_sql.SQL("DROP DATABASE IF EXISTS {}").format(pg_sql.Identifier(database)))
        conn.execute(
            pg_sql.SQL("CREATE DATABASE {} OWNER postgres").format(pg_sql.Identifier(database))
        )


def _plant_serial_legacy() -> None:
    with psycopg.connect(_admin(SERIAL_DB), autocommit=True) as conn:
        conn.execute(
            "CREATE TABLE public.serial_legacy (id SERIAL PRIMARY KEY, label text NOT NULL)"
        )
        conn.execute("INSERT INTO public.serial_legacy (label) VALUES ('seed')")
        conn.execute("ALTER TABLE public.serial_legacy OWNER TO postgres")


def _plant_identity_legacy() -> None:
    with psycopg.connect(_admin(IDENTITY_DB), autocommit=True) as conn:
        conn.execute(
            """
            CREATE TABLE public.identity_legacy (
              id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              label text NOT NULL
            )
            """
        )
        conn.execute("INSERT INTO public.identity_legacy (label) VALUES ('seed')")
        conn.execute("ALTER TABLE public.identity_legacy OWNER TO postgres")


def seed_cross_ponds() -> CrossPonds:
    _ensure_postgres_role()
    _drop_console_role()
    _recreate_database(SERIAL_DB)
    _recreate_database(IDENTITY_DB)
    _plant_serial_legacy()
    _plant_identity_legacy()

    reset_pond_tables()
    ensure_demo_user()

    engine = create_engine(to_sync_database_url(get_settings().database_url))
    with engine.begin() as connection:
        connection.execute(text("DELETE FROM sql_history"))
        user_id = connection.execute(
            text("SELECT id FROM users WHERE email = :email"),
            {"email": DEMO_EMAIL},
        ).scalar_one()
        connection.execute(
            text(
                """
                INSERT INTO nodes (id, public_host, status, capacity_ponds, token_hash)
                VALUES (:id, :host, 'alive', 20, :token_hash)
                """
            ),
            {
                "id": "node-sql-cross",
                "host": HOST,
                "token_hash": hash_token("sql-cross-node"),
            },
        )
        serial_id = uuid4()
        identity_id = uuid4()
        encrypted = encrypt_secret(POND_PASSWORD)
        for pond_id, name, port in (
            (serial_id, SERIAL_NAME, PORT_SERIAL),
            (identity_id, IDENTITY_NAME, PORT_IDENTITY),
        ):
            connection.execute(
                text(
                    """
                    INSERT INTO ponds (
                        id, user_id, plan_id, node_id, name, engine_version,
                        desired_state, host_port, db_password_encrypted
                    )
                    VALUES (
                        :id, :user_id, 'micro', 'node-sql-cross', :name, '16',
                        'running', :port, :password
                    )
                    """
                ),
                {
                    "id": pond_id,
                    "user_id": user_id,
                    "name": name,
                    "port": port,
                    "password": encrypted,
                },
            )
            connection.execute(
                text(
                    """
                    INSERT INTO pond_status (pond_id, observed_state, healthy, updated_at)
                    VALUES (:id, 'running', true, CURRENT_TIMESTAMP)
                    """
                ),
                {"id": pond_id},
            )
    engine.dispose()
    return CrossPonds(serial_id=serial_id, identity_id=identity_id, user_id=UUID(str(user_id)))


async def _login(http: httpx.AsyncClient) -> dict[str, str]:
    response = await http.post(
        "/api/v1/auth/login",
        json={"email": DEMO_EMAIL, "password": DEMO_PASSWORD},
    )
    assert response.status_code == 200, response.text
    return {"Authorization": f"Bearer {response.json()['access_token']}"}


async def _sql(
    http: httpx.AsyncClient,
    headers: dict[str, str],
    pond_id: UUID,
    query: str,
    *,
    mode: str = "write",
) -> httpx.Response:
    return await http.post(
        f"/api/v1/ponds/{pond_id}/sql",
        headers=headers,
        json={"query": query, "mode": mode},
    )


async def _parallel_first_create(pond_id: UUID, table: str) -> list[httpx.Response]:
    transport = ASGITransport(app=app)
    async with httpx.AsyncClient(transport=transport, base_url="http://test") as http:
        headers = await _login(http)
        return list(
            await asyncio.gather(
                *[
                    _sql(
                        http,
                        headers,
                        pond_id,
                        f"INSERT INTO public.{table} (label) VALUES ('p{i}') RETURNING id",
                    )
                    for i in range(PARALLEL_N)
                ]
            )
        )


def _assert_console_isolated_from(database: str, port: int) -> None:
    password = console_role_password(POND_PASSWORD)
    with pytest.raises(psycopg.OperationalError) as raised:
        psycopg.connect(
            f"postgresql://{CONSOLE_ROLE}:{password}@{HOST}:{port}/{database}",
            connect_timeout=5,
        )
    message = str(raised.value).lower()
    assert "authentication failed" not in message


@pytest.mark.asyncio
async def test_cross_pond_serial_then_identity_first_create_and_isolation() -> None:
    ponds = seed_cross_ponds()

    serial_first = await _parallel_first_create(ponds.serial_id, "serial_legacy")
    serial_statuses = [response.status_code for response in serial_first]
    assert serial_statuses == [200] * PARALLEL_N, [
        (response.status_code, response.text) for response in serial_first
    ]
    serial_ids = sorted(int(response.json()["rows"][0][0]) for response in serial_first)
    assert serial_ids == list(range(2, PARALLEL_N + 2))

    # After repairing the SERIAL pond, koi_console must not reach the IDENTITY DB.
    _assert_console_isolated_from(IDENTITY_DB, PORT_IDENTITY)

    identity_first = await _parallel_first_create(ponds.identity_id, "identity_legacy")
    identity_statuses = [response.status_code for response in identity_first]
    assert identity_statuses == [200] * PARALLEL_N, [
        (response.status_code, response.text) for response in identity_first
    ]
    identity_ids = sorted(int(response.json()["rows"][0][0]) for response in identity_first)
    assert identity_ids == list(range(2, PARALLEL_N + 2))

    # After IDENTITY repair, CONNECT on SERIAL is revoked again (isolation).
    _assert_console_isolated_from(SERIAL_DB, PORT_SERIAL)

    transport = ASGITransport(app=app)
    async with httpx.AsyncClient(transport=transport, base_url="http://test") as http:
        headers = await _login(http)
        for _ in range(3):
            serial_read = await _sql(
                http,
                headers,
                ponds.serial_id,
                "SELECT count(*) FROM public.serial_legacy",
                mode="read",
            )
            identity_read = await _sql(
                http,
                headers,
                ponds.identity_id,
                "SELECT count(*) FROM public.identity_legacy",
                mode="read",
            )
            assert serial_read.status_code == 200, serial_read.text
            assert identity_read.status_code == 200, identity_read.text
            assert serial_read.json()["rows"] == [[PARALLEL_N + 1]]
            assert identity_read.json()["rows"] == [[PARALLEL_N + 1]]

        serial_again = await _sql(
            http,
            headers,
            ponds.serial_id,
            "INSERT INTO public.serial_legacy (label) VALUES ('alt') RETURNING id",
        )
        identity_again = await _sql(
            http,
            headers,
            ponds.identity_id,
            "INSERT INTO public.identity_legacy (label) VALUES ('alt') RETURNING id",
        )
        assert serial_again.status_code == 200, serial_again.text
        assert identity_again.status_code == 200, identity_again.text
        assert serial_again.json()["rows"] == [[PARALLEL_N + 2]]
        assert identity_again.json()["rows"] == [[PARALLEL_N + 2]]
